typedef ChunkIdMapType = Map<String, String>;

class DartExceptionProcessor {
  /// Maximum number of exception items in `$exception_list` when walking an
  /// error's cause chain (outermost error plus its causes).
  static const maxExceptionChainLength = 10;

  static final _aotBuildId = RegExp(
    r"^[ \t]*build_id[:=][ \t]*'([0-9a-fA-F]+)'",
    multiLine: true,
  );
  static final _aotImageBase = RegExp(
    r'^[ \t]*isolate_dso_base[:=][ \t]*(?:0x)?([0-9a-fA-F]+)',
    multiLine: true,
  );
  static final _aotFrame = RegExp(
    r'^[ \t]*#[0-9]+[ \t]+abs[ \t]+([0-9a-fA-F]+)(?:[ \t]|$)',
  );
  static final _aotLoadingUnitFrame = RegExp(
    r'^[ \t]*#[0-9]+[ \t]+abs[ \t]+[0-9a-fA-F]+[ \t]+unit(?:[ \t]|$)',
  );
  static final _firstFrame = RegExp(
    r'^[ \t]*#[0-9]+[ \t]+',
    multiLine: true,
  );

  /// Converts Dart error/exception and stack trace to PostHog exception format
  static Map<String, dynamic> processException({
    required Object error,
    StackTrace? stackTrace,
    Map<String, Object>? properties,
    List<String>? inAppIncludes,
    List<String>? inAppExcludes,
    bool inAppByDefault = true,
    StackTrace Function()? stackTraceProvider, //for testing
  }) {
    // Extract PostHog metadata if error is wrapped in PostHogException
    var mechanismType = 'generic';
    var handled = true;
    var currentError = error;

    if (error is PostHogException) {
      handled = error.handled;
      mechanismType = error.mechanism;
      currentError = error.source;
    }

    StackTrace? effectiveStackTrace = stackTrace;
    bool isGeneratedStackTrace = false;

    // If no usable trace was supplied, try the error's own stackTrace
    if (effectiveStackTrace == null ||
        effectiveStackTrace.toString().trim().isEmpty) {
      effectiveStackTrace = _extractOwnStackTrace(currentError);
    }

    // If still null, get current stack trace
    if (effectiveStackTrace == null) {
      effectiveStackTrace = stackTraceProvider?.call() ?? StackTrace.current;
      isGeneratedStackTrace = true; // Flag to remove top PostHog frames
    }

    // Check if we still have an empty stack trace
    final hasValidStackTrace = effectiveStackTrace.toString().trim().isNotEmpty;

    // Process primary exception
    final parsedTrace = hasValidStackTrace
        ? _parseStackTrace(
            effectiveStackTrace,
            inAppIncludes: inAppIncludes,
            inAppExcludes: inAppExcludes,
            inAppByDefault: inAppByDefault,
            removeTopPostHogFrames: isGeneratedStackTrace,
          )
        : null;
    final frames = parsedTrace?.frames ?? <Map<String, dynamic>>[];
    final debugImages = <Map<String, dynamic>>[];
    if (parsedTrace?.debugImage case final image?) {
      debugImages.add(image);
    }

    final errorType = _getExceptionType(currentError);

    // Mark exception as synthetic if:
    // - runtimeType.toString() returned empty/null (fallback to 'Error' type)
    // - Stack trace was generated by PostHog (not from original exception)
    // - No valid stack trace is available
    final isSynthetic =
        errorType == null || isGeneratedStackTrace || !hasValidStackTrace;

    final exceptionData = <String, dynamic>{
      'type': errorType ?? 'Error',
      'mechanism': {
        'handled': handled,
        'synthetic': isSynthetic,
        'type': mechanismType,
      },
    };

    // Add exception message, if available
    final errorMessage = currentError.toString();
    if (errorMessage.isNotEmpty) {
      exceptionData['value'] = errorMessage;
    }

    // Add stacktrace, if any frames are available
    if (frames.isNotEmpty) {
      exceptionData['stacktrace'] = {'frames': frames, 'type': 'raw'};
    }

    // Add thread ID, if available
    final threadId = _getCurrentThreadId();
    if (threadId != null) {
      exceptionData['thread_id'] = threadId;
    }

    // Walk the error's cause chain into additional exception items,
    // outermost-first (wrapper first, root cause last)
    final exceptionList = <Map<String, dynamic>>[exceptionData];
    _appendCauses(
      exceptionList,
      currentError,
      handled: handled,
      mechanismType: mechanismType,
      threadId: threadId,
      inAppIncludes: inAppIncludes,
      inAppExcludes: inAppExcludes,
      inAppByDefault: inAppByDefault,
      debugImages: debugImages,
    );

    // Final result, merging system properties with user properties (user properties take precedence)
    final result = <String, dynamic>{
      '\$exception_level': 'error', // Never crashes, so always error
      '\$exception_list': exceptionList,
      if (properties != null) ...properties,
    };
    result.remove('\$debug_images');
    if (debugImages.isNotEmpty) {
      result['\$debug_images'] = debugImages;
    }

    return result;
  }

  /// Appends one exception item per cause of [error] to [exceptionList],
  /// outermost-first, guarding against cycles and capping the chain at
  /// [maxExceptionChainLength] items.
  static void _appendCauses(
    List<Map<String, dynamic>> exceptionList,
    Object error, {
    required bool handled,
    required String mechanismType,
    required int? threadId,
    List<String>? inAppIncludes,
    List<String>? inAppExcludes,
    bool inAppByDefault = true,
    required List<Map<String, dynamic>> debugImages,
  }) {
    final seen = Set<Object>.identity()..add(error);
    _appendCauseItems(
      exceptionList,
      _getCauses(error),
      seen,
      handled: handled,
      mechanismType: mechanismType,
      threadId: threadId,
      inAppIncludes: inAppIncludes,
      inAppExcludes: inAppExcludes,
      inAppByDefault: inAppByDefault,
      debugImages: debugImages,
    );
  }

  static void _appendCauseItems(
    List<Map<String, dynamic>> exceptionList,
    Iterable<Object> causes,
    Set<Object> seen, {
    required bool handled,
    required String mechanismType,
    required int? threadId,
    List<String>? inAppIncludes,
    List<String>? inAppExcludes,
    bool inAppByDefault = true,
    required List<Map<String, dynamic>> debugImages,
  }) {
    for (final cause in causes) {
      if (exceptionList.length >= maxExceptionChainLength || !seen.add(cause)) {
        continue;
      }

      final causeType = _getExceptionType(cause);
      final causeData = <String, dynamic>{
        'type': causeType ?? 'Error',
        'mechanism': {
          'handled': handled,
          'synthetic': causeType == null,
          'type': mechanismType,
        },
      };

      final causeMessage = cause.toString();
      if (causeMessage.isNotEmpty) {
        causeData['value'] = causeMessage;
      }

      // Only use the cause's own stack trace; never generate one for causes
      final causeStackTrace = _extractOwnStackTrace(cause);
      if (causeStackTrace != null) {
        final parsedTrace = _parseStackTrace(
          causeStackTrace,
          inAppIncludes: inAppIncludes,
          inAppExcludes: inAppExcludes,
          inAppByDefault: inAppByDefault,
        );
        if (parsedTrace.frames.isNotEmpty) {
          causeData['stacktrace'] = {
            'frames': parsedTrace.frames,
            'type': 'raw',
          };
        }
        if (parsedTrace.debugImage case final image?) {
          if (!debugImages.any(
            (existing) =>
                existing['debug_id'] == image['debug_id'] &&
                existing['image_addr'] == image['image_addr'],
          )) {
            debugImages.add(image);
          }
        }
      }

      if (threadId != null) {
        causeData['thread_id'] = threadId;
      }

      exceptionList.add(causeData);
      _appendCauseItems(
        exceptionList,
        _getCauses(cause),
        seen,
        handled: handled,
        mechanismType: mechanismType,
        threadId: threadId,
        inAppIncludes: inAppIncludes,
        inAppExcludes: inAppExcludes,
        inAppByDefault: inAppByDefault,
        debugImages: debugImages,
      );
    }
  }

  /// Extracts the causes of an error, if the error type exposes any.
  ///
  /// Supports [AsyncError] (unwraps to the original error),
  /// [ParallelWaitError] (walks all non-null errors) and the common duck-typed
  /// `cause` getter convention used by custom exceptions.
  static Iterable<Object> _getCauses(Object error) sync* {
    if (error is AsyncError) {
      yield error.error;
      return;
    }

    if (error is ParallelWaitError) {
      yield* _parallelErrors(error.errors);
      return;
    }

    try {
      // ignore: avoid_dynamic_calls
      final cause = (error as dynamic).cause;
      if (cause is Object && !identical(cause, error)) {
        yield cause;
      }
    } catch (_) {
      // Error type doesn't expose a `cause` getter
    }
  }

  /// Returns all non-null errors from a [ParallelWaitError.errors] collection,
  /// if it is enumerable (e.g. `List<Future>.wait` produces a
  /// `List<AsyncError?>`; record-based `wait` produces a record, skipped here)
  static Iterable<Object> _parallelErrors(Object? errors) sync* {
    if (errors is Iterable) {
      for (final error in errors) {
        if (error != null) {
          yield error as Object;
        }
      }
    }
  }

  /// Returns the error's own stack trace, if it carries a usable one
  static StackTrace? _extractOwnStackTrace(Object error) {
    StackTrace? stackTrace;
    if (error is AsyncError) {
      stackTrace = error.stackTrace;
    } else if (error is Error) {
      stackTrace = error.stackTrace;
    }

    if (stackTrace == null || stackTrace.toString().trim().isEmpty) {
      return null;
    }
    return stackTrace;
  }

  /// Determines if a stack frame belongs to PostHog SDK (just check package for now)
  static bool _isPostHogFrame(Frame frame) {
    return frame.package == 'posthog_flutter';
  }

  /// Asynchronous gap frame for separating async traces
  static const _asynchronousGapFrame = <String, dynamic>{
    'platform': 'dart',
    'abs_path': '<asynchronous suspension>',
    'in_app': false,
    'synthetic': true,
  };

  /// Parses stack trace into PostHog format
  ///
  /// Approach inspired by Sentry's stack trace factory implementation:
  /// https://github.com/getsentry/sentry-dart/blob/a69a51fd1695dd93024be80a50ad05dd990b2b82/packages/dart/lib/src/sentry_stack_trace_factory.dart#L29-L53
  static ({List<Map<String, dynamic>> frames, Map<String, dynamic>? debugImage})
      _parseStackTrace(
    StackTrace stackTrace, {
    List<String>? inAppIncludes,
    List<String>? inAppExcludes,
    bool inAppByDefault = true,
    bool removeTopPostHogFrames = false,
  }) {
    final traceText = stackTrace.toString();
    final aotImage = _parseAotImage(traceText);
    final firstFrame =
        aotImage == null ? null : _firstFrame.firstMatch(traceText);
    final chain = firstFrame == null
        ? Chain.forTrace(stackTrace)
        : Chain.parse(traceText.substring(firstFrame.start));
    final frames = <Map<String, dynamic>>[];
    final chunkIdMap = getPosthogChunkIds() ?? {};
    var hasNativeFrame = false;

    for (final (index, trace) in chain.traces.indexed) {
      bool skipNextPostHogFrame = removeTopPostHogFrames;

      for (final frame in trace.frames) {
        // Skip top PostHog frames?
        if (skipNextPostHogFrame) {
          if (_isPostHogFrame(frame)) {
            continue;
          }
          skipNextPostHogFrame = false;
        }

        // A deferred loading unit needs its own build ID and image base.
        final nativeAddress = aotImage != null &&
                frame is UnparsedFrame &&
                !_aotLoadingUnitFrame.hasMatch(frame.member)
            ? _aotFrame.firstMatch(frame.member)?.group(1)
            : null;
        final instructionAddress = nativeAddress == null
            ? null
            : int.tryParse(nativeAddress, radix: 16);
        final imageBase = aotImage == null
            ? null
            : int.parse(aotImage.imageAddr.substring(2), radix: 16);
        final Map<String, dynamic>? processedFrame;
        if (instructionAddress != null &&
            imageBase != null &&
            instructionAddress >= imageBase) {
          processedFrame = {
            'platform': 'native',
            'lang': 'dart',
            'instruction_addr': '0x${instructionAddress.toRadixString(16)}',
            'image_addr': aotImage!.imageAddr,
            'in_app': inAppByDefault,
          };
          hasNativeFrame = true;
        } else {
          processedFrame = _convertFrameToPostHog(
            frame,
            chunkIdMap,
            inAppIncludes: inAppIncludes,
            inAppExcludes: inAppExcludes,
            inAppByDefault: inAppByDefault,
          );
        }
        if (processedFrame != null) {
          frames.add(processedFrame);
        }
      }

      // Add asynchronous gap frame between traces (skipping last trace)
      if (index < chain.traces.length - 1) {
        frames.add(_asynchronousGapFrame);
      }
    }

    // The stack_trace package yields frames innermost-first (crash site first,
    // entry point last). PostHog's canonical wire order is bottom-up:
    // frames[0] is the outermost/entry point and the last frame is the crash
    // site. Reverse to match; this also keeps async gap frames positioned
    // correctly between their surrounding traces.
    return (
      frames: frames.reversed.toList(),
      debugImage: hasNativeFrame
          ? <String, dynamic>{
              'debug_id': aotImage!.debugId,
              'image_addr': aotImage.imageAddr,
              'type': aotImage.imageType,
            }
          : null,
    );
  }

  static ({String debugId, String imageAddr, String imageType})? _parseAotImage(
    String traceText,
  ) {
    if (kIsWeb) {
      return null;
    }
    final buildId = _aotBuildId.firstMatch(traceText)?.group(1);
    final base = _aotImageBase.firstMatch(traceText)?.group(1);
    if (buildId == null || base == null || buildId.length < 32) {
      return null;
    }
    final imageBase = int.tryParse(base, radix: 16);
    if (imageBase == null) {
      return null;
    }

    String debugId;
    String imageType;
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        final normalizedId = buildId.toLowerCase();
        final bytes = [
          for (var i = 0; i < 32; i += 2) normalizedId.substring(i, i + 2),
        ];
        debugId = '${bytes[3]}${bytes[2]}${bytes[1]}${bytes[0]}-'
            '${bytes[5]}${bytes[4]}-${bytes[7]}${bytes[6]}-'
            '${bytes[8]}${bytes[9]}-${bytes.skip(10).join()}';
        imageType = 'elf';
      case TargetPlatform.iOS:
        if (buildId.length != 32) {
          return null;
        }
        debugId = ('${buildId.substring(0, 8)}-${buildId.substring(8, 12)}-'
                '${buildId.substring(12, 16)}-${buildId.substring(16, 20)}-'
                '${buildId.substring(20)}')
            .toUpperCase();
        imageType = 'macho';
      default:
        return null;
    }
    return (
      debugId: debugId,
      imageAddr: '0x${imageBase.toRadixString(16)}',
      imageType: imageType,
    );
  }

  /// Converts a Frame from stack_trace package to PostHog format
  static Map<String, dynamic>? _convertFrameToPostHog(
    Frame frame,
    Map<String, String> chunkIdMap, {
    List<String>? inAppIncludes,
    List<String>? inAppExcludes,
    bool inAppByDefault = true,
  }) {
    final absPath = '$eventOrigin${_extractAbsolutePath(frame)}';
    final frameData = <String, dynamic>{
      'platform': kIsWeb ? 'web:javascript' : 'dart',
      'abs_path': absPath,
      'in_app': _isInAppFrame(
        frame,
        inAppIncludes: inAppIncludes,
        inAppExcludes: inAppExcludes,
        inAppByDefault: inAppByDefault,
      ),
    };

    // add package, if available
    final package = _extractPackage(frame);
    if (package != null && package.isNotEmpty) {
      frameData['package'] = package;
    }

    // add function, if available
    final member = frame.member;
    if (member != null && member.isNotEmpty) {
      frameData['function'] = member;
    }

    // Add filename, if available
    final fileName = _extractFileName(frame);
    if (fileName != null && fileName.isNotEmpty) {
      frameData['filename'] = fileName;

      // Check if any key in chunkIdMap contains the fileName as a substring
      String? chunkId;
      for (final entry in chunkIdMap.entries) {
        if (entry.key.contains(fileName)) {
          chunkId = entry.value;
          printIfDebug('chunkId found: $chunkId for fileName: $fileName');
          break;
        }
      }
      if (chunkId != null) {
        frameData['chunk_id'] = chunkId;
      }
    }

    // Add line number, if available
    final line = frame.line;
    if (line != null && line >= 0) {
      frameData['lineno'] = line;
    }

    // Add column number, if available
    final column = frame.column;
    if (column != null && column >= 0) {
      frameData['colno'] = column;
    }

    return frameData;
  }

  /// Determines if a frame is considered in-app
  static bool _isInAppFrame(
    Frame frame, {
    List<String>? inAppIncludes,
    List<String>? inAppExcludes,
    bool inAppByDefault = true,
  }) {
    final scheme = frame.uri.scheme;

    if (scheme.isEmpty) {
      // Early bail out for unknown schemes
      return inAppByDefault;
    }

    final package = frame.package;
    if (package != null) {
      // 1. Check inAppIncludes first (highest priority)
      if (inAppIncludes != null && inAppIncludes.contains(package)) {
        return true;
      }

      // 2. Check inAppExcludes second
      if (inAppExcludes != null && inAppExcludes.contains(package)) {
        return false;
      }
    }

    // 3. Hardcoded exclusions
    if (frame.isCore) {
      // dart: packages
      return false;
    }

    if (frame.package == 'flutter') {
      // flutter package
      return false;
    }

    // 4. Default fallback
    return inAppByDefault;
  }

  static String? _extractPackage(Frame frame) {
    return frame.package;
  }

  static String? _extractFileName(Frame frame) {
    return frame.uri.pathSegments.isNotEmpty
        ? frame.uri.pathSegments.last
        : null;
  }

  static String _extractAbsolutePath(Frame frame) {
    // For privacy, only return filename for local file paths
    if (frame.uri.scheme != 'dart' &&
        frame.uri.scheme != 'package' &&
        frame.uri.pathSegments.isNotEmpty) {
      return frame.uri.pathSegments.last; // Just filename for privacy
    }

    // For dart: and package: URIs, full path is safe
    return frame.uri.toString();
  }

  /// Gets the current thread ID using isolate-based detection
  static int? _getCurrentThreadId() {
    try {
      // Check if we're in the root isolate (main thread)
      if (isolate_utils.isRootIsolate()) {
        return 'main'.hashCode;
      }

      // For other isolates, use the isolate's debug name
      final isolateName = isolate_utils.getIsolateName();
      if (isolateName != null && isolateName.isNotEmpty) {
        return isolateName.hashCode;
      }

      return null;
    } catch (e) {
      return null;
    }
  }

  static String? _getExceptionType(Object error) {
    // The string is only intended for providing information to a reader while debugging. There is no guaranteed format, the string value returned for a Type instances is entirely implementation dependent.
    final type = error.runtimeType.toString();
    return type.isNotEmpty ? type : null;
  }
}
